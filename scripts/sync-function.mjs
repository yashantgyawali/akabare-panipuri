#!/usr/bin/env node
/**
 * Copies the pure engine + server core into the edge function bundle:
 *
 *   src/engine/*.ts (no tests)            → supabase/functions/game/_lib/engine/
 *   src/server/{types,core,crypto}.ts     → supabase/functions/game/_lib/server/
 *
 * The layout mirrors src/, so relative imports like '../engine/index.ts' keep
 * resolving. _lib is wiped first so deleted sources don't linger. Run before
 * every deploy: `npm run sync:function`.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lib = join(root, 'supabase/functions/game/_lib');

const engineDir = join(root, 'src/engine');
const engineFiles = readdirSync(engineDir)
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts') && statSync(join(engineDir, f)).isFile())
  .sort()
  .map((f) => join(engineDir, f));
const serverFiles = ['types.ts', 'core.ts', 'crypto.ts'].map((f) => join(root, 'src/server', f));

rmSync(lib, { recursive: true, force: true });

const copied = [];
for (const [files, sub] of [
  [engineFiles, 'engine'],
  [serverFiles, 'server'],
]) {
  mkdirSync(join(lib, sub), { recursive: true });
  for (const src of files) {
    const dest = join(lib, sub, basename(src));
    const banner = `// GENERATED by scripts/sync-function.mjs from ${relative(root, src)}. Edit the source, not this copy.\n`;
    writeFileSync(dest, banner + readFileSync(src, 'utf8'));
    copied.push(relative(root, dest));
  }
}

console.log(`Synced ${copied.length} files into ${relative(root, lib)}/:`);
for (const f of copied) console.log(`  ${f}`);
